// A small, readable AArch64 backend that walks the typed AST directly.
//
// Strategy (deliberately simple, see README "AArch64 backend"):
//  * Every expression leaves its value in w0 (int/bool) or s0 (float).
//  * Binary operators evaluate the LHS, park it on the stack (16-byte slots keep
//    sp aligned as AAPCS64 requires), evaluate the RHS, then pop the LHS into
//    w1/s1. A leaf RHS (literal or variable) skips the stack round-trip.
//  * Mini-C has no pointers, so no variable's address is ever taken: locals can
//    live in callee-saved registers (w19-w28, s8-s15) for their whole lifetime.
//    The most heavily used ones (weighted by loop depth) get registers, which
//    calls preserve for free; any overflow gets a 4-byte slot below x29.
//  * Calls follow AAPCS64: the first 8 integer args go in w0-w7, the first 8 float
//    args in s0-s7, the rest on the stack. Apple's ABI packs stack args at their
//    natural alignment while the generic ABI uses 8-byte slots; both are handled.
#include "codegen_aarch64.h"
#include <cstdint>
#include <algorithm>
#include <cmath>
#include <cstdio>
#include <cstring>
#include <unordered_map>

namespace {

class A64 {
public:
  A64(AArch64OS os, const std::vector<std::string> &lines) : darwin(os == AArch64OS::Darwin), src(lines) {}

  std::string run(const Program &p) {
    out += "// Generated by mccomp's hand-written AArch64 backend (" +
           std::string(darwin ? "Apple arm64" : "Linux aarch64") + ")\n";
    out += darwin ? "\t.section\t__TEXT,__text,regular,pure_instructions\n" : "\t.text\n";
    for (auto &item : p.items)
      if (item.function && !item.function->isExtern()) function(*item.function);
    for (auto &item : p.items)
      if (item.global) global(*item.global);
    if (!darwin) out += "\t.section\t.note.GNU-stack,\"\",@progbits\n";
    return out;
  }

private:
  bool darwin;
  const std::vector<std::string> &src;
  std::string out;
  std::unordered_map<const VarDecl *, int> slot;         // positive offset below x29
  std::unordered_map<const VarDecl *, std::string> reg;  // register-allocated locals
  std::vector<std::pair<std::string, int>> savedRegs;    // callee-saved reg -> save offset
  int labelCount = 0;
  std::string retLabel;
  int lastLine = 0;

  std::string sym(const std::string &n) const { return darwin ? "_" + n : n; }
  std::string newLabel(const char *hint) { return (darwin ? "L" : ".L") + std::string(hint) + std::to_string(labelCount++); }
  void ins(const std::string &s) { out += "\t" + s + "\n"; }
  void label(const std::string &l) { out += l + ":\n"; }
  static bool isFloat(Type t) { return t == Type::Float; }
  static std::string imm(long v) { return "#" + std::to_string(v); }

  void annotate(SrcLoc loc) {
    if (loc.line <= 0 || loc.line == lastLine || loc.line > (int)src.size()) return;
    lastLine = loc.line;
    std::string text = src[loc.line - 1];
    size_t b = text.find_first_not_of(" \t");
    text = b == std::string::npos ? "" : text.substr(b);
    out += "\t// line " + std::to_string(loc.line) + ": " + text + "\n";
  }

  //===--- Data ------------------------------------------------------------===//

  void global(const VarDecl &v) {
    out += "\n";
    if (darwin) ins(".comm\t" + sym(v.name) + ",4,2");
    else ins(".comm\t" + v.name + ",4,4");
  }

  // Leaves the address of a global in x9.
  void globalAddr(const std::string &name) {
    if (darwin) {
      ins("adrp\tx9, " + sym(name) + "@PAGE");
      ins("add\tx9, x9, " + sym(name) + "@PAGEOFF");
    } else {
      ins("adrp\tx9, " + name);
      ins("add\tx9, x9, :lo12:" + name);
    }
  }

  // Memory operand for a variable's home; may emit a helper instruction into x9.
  std::string home(const VarDecl &v) {
    if (v.isGlobal) {
      globalAddr(v.name);
      return "[x9]";
    }
    int off = slot.at(&v);
    if (off <= 256) return "[x29, " + imm(-off) + "]";
    ins("sub\tx9, x29, " + imm(off));
    return "[x9]";
  }

  std::string regOf(const Expr &e) const {
    if (e.kind != Expr::VarRef) return "";
    auto it = reg.find(static_cast<const VarRefExpr &>(e).decl);
    return it == reg.end() ? "" : it->second;
  }

  void move(const std::string &dst, const std::string &src, bool fp) {
    if (dst != src) ins((fp ? "fmov\t" : "mov\t") + dst + ", " + src);
  }

  void load(const VarDecl &v, const char *dst) {
    auto r = reg.find(&v);
    if (r != reg.end()) return move(dst, r->second, isFloat(v.type));
    std::string mem = home(v);
    bool unscaled = mem.rfind("[x29", 0) == 0;
    ins(std::string(unscaled ? "ldur\t" : "ldr\t") + dst + ", " + mem);
  }
  void store(const VarDecl &v, const char *srcReg) {
    auto r = reg.find(&v);
    if (r != reg.end()) return move(r->second, srcReg, isFloat(v.type));
    std::string mem = home(v);
    bool unscaled = mem.rfind("[x29", 0) == 0;
    ins(std::string(unscaled ? "stur\t" : "str\t") + srcReg + ", " + mem);
  }

  void push(Type t) { ins(std::string("str\t") + (isFloat(t) ? "s0" : "w0") + ", [sp, #-16]!"); }
  void pop(Type t, const char *intReg, const char *fpReg) {
    ins(std::string("ldr\t") + (isFloat(t) ? fpReg : intReg) + ", [sp], #16");
  }

  void movImm32(const char *reg, uint32_t v) {
    uint32_t lo = v & 0xffff, hi = v >> 16;
    if (hi == 0) {
      ins(std::string("mov\t") + reg + ", " + imm(lo));
    } else if (hi == 0xffff && (lo & 0x8000)) {
      ins(std::string("mov\t") + reg + ", " + imm((int32_t)v)); // movn form
    } else {
      ins(std::string("movz\t") + reg + ", " + imm(lo));
      ins(std::string("movk\t") + reg + ", " + imm(hi) + ", lsl #16");
    }
  }

  //===--- Functions -------------------------------------------------------===//

  // Stack-argument layout. Generic AAPCS64: every stack arg takes an 8-byte slot.
  // Apple arm64: args are packed at their natural size/alignment.
  struct ArgLoc {
    bool inReg;
    int reg;    // register number when inReg
    int offset; // byte offset in the outgoing/incoming stack area otherwise
  };
  std::vector<ArgLoc> layoutArgs(const std::vector<Type> &types, int &stackBytes) const {
    std::vector<ArgLoc> locs;
    int ngrn = 0, nsrn = 0;
    stackBytes = 0;
    for (Type t : types) {
      int &counter = isFloat(t) ? nsrn : ngrn;
      if (counter < 8) {
        locs.push_back({true, counter++, 0});
        continue;
      }
      int size = darwin ? (t == Type::Bool ? 1 : 4) : 8;
      stackBytes = (stackBytes + size - 1) / size * size;
      locs.push_back({false, 0, stackBytes});
      stackBytes += size;
    }
    stackBytes = (stackBytes + 15) / 16 * 16;
    return locs;
  }

  void collectLocals(const BlockStmt &b, std::vector<const VarDecl *> &vars) {
    for (auto &v : b.locals) vars.push_back(v.get());
    for (auto &s : b.stmts) collectStmtLocals(*s, vars);
  }
  void collectStmtLocals(const Stmt &s, std::vector<const VarDecl *> &vars) {
    if (s.kind == Stmt::BlockS) collectLocals(static_cast<const BlockStmt &>(s), vars);
    else if (s.kind == Stmt::IfS) {
      auto &i = static_cast<const IfStmt &>(s);
      collectLocals(*i.thenB, vars);
      if (i.elseB) collectLocals(*i.elseB, vars);
    } else if (s.kind == Stmt::WhileS) {
      collectStmtLocals(*static_cast<const WhileStmt &>(s).body, vars);
    }
  }

  void adjustSp(const char *op, int bytes) {
    while (bytes > 0) {
      int chunk = bytes > 4080 ? 4080 : bytes;
      ins(std::string(op) + "\tsp, sp, " + imm(chunk));
      bytes -= chunk;
    }
  }

  // Use counts weighted by 8^loop-depth: a crude but effective spill heuristic.
  std::unordered_map<const VarDecl *, double> weight;
  void countExpr(const Expr &e, double w) {
    switch (e.kind) {
    case Expr::VarRef: weight[static_cast<const VarRefExpr &>(e).decl] += w; break;
    case Expr::Assign: {
      auto &a = static_cast<const AssignExpr &>(e);
      weight[a.decl] += w;
      countExpr(*a.value, w);
      break;
    }
    case Expr::Unary: countExpr(*static_cast<const UnaryExpr &>(e).operand, w); break;
    case Expr::Binary: {
      auto &b = static_cast<const BinaryExpr &>(e);
      countExpr(*b.lhs, w);
      countExpr(*b.rhs, w);
      break;
    }
    case Expr::Call:
      for (auto &a : static_cast<const CallExpr &>(e).args) countExpr(*a, w);
      break;
    case Expr::Cast: countExpr(*static_cast<const CastExpr &>(e).operand, w); break;
    default: break;
    }
  }
  void countStmt(const Stmt &s, double w) {
    switch (s.kind) {
    case Stmt::ExprS:
      if (auto &e = static_cast<const ExprStmt &>(s).expr) countExpr(*e, w);
      break;
    case Stmt::BlockS:
      for (auto &x : static_cast<const BlockStmt &>(s).stmts) countStmt(*x, w);
      break;
    case Stmt::IfS: {
      auto &i = static_cast<const IfStmt &>(s);
      countExpr(*i.cond, w);
      countStmt(*i.thenB, w);
      if (i.elseB) countStmt(*i.elseB, w);
      break;
    }
    case Stmt::WhileS: {
      auto &wh = static_cast<const WhileStmt &>(s);
      countExpr(*wh.cond, w * 8);
      countStmt(*wh.body, w * 8);
      break;
    }
    case Stmt::ReturnS:
      if (auto &v = static_cast<const ReturnStmt &>(s).value) countExpr(*v, w);
      break;
    }
  }

  void allocate(const FunctionDecl &f, std::vector<const VarDecl *> vars) {
    weight.clear();
    countStmt(*f.body, 1);
    std::stable_sort(vars.begin(), vars.end(),
                     [&](const VarDecl *a, const VarDecl *b) { return weight[a] > weight[b]; });
    int nextInt = 19, nextFp = 8;
    for (auto *v : vars) {
      if (weight[v] == 0 && !v->isParam) continue; // never used: needs no storage at all
      if (isFloat(v->type) && nextFp <= 15) {
        reg[v] = "s" + std::to_string(nextFp);
        savedRegs.push_back({"d" + std::to_string(nextFp++), 0});
      } else if (!isFloat(v->type) && nextInt <= 28) {
        reg[v] = "w" + std::to_string(nextInt);
        savedRegs.push_back({"x" + std::to_string(nextInt++), 0});
      }
    }
  }

  void function(const FunctionDecl &f) {
    std::vector<const VarDecl *> vars;
    for (auto &p : f.params) vars.push_back(p.get());
    collectLocals(*f.body, vars);
    slot.clear();
    reg.clear();
    savedRegs.clear();
    allocate(f, vars);
    int off = 0;
    for (auto *v : vars)
      if (!reg.count(v)) slot[v] = (off += 4);
    off = (off + 7) / 8 * 8;
    for (auto &r : savedRegs) r.second = (off += 8);
    int frame = (off + 15) / 16 * 16;
    retLabel = newLabel("ret_");
    lastLine = 0;

    std::string name = sym(f.name);
    out += "\n";
    ins(".globl\t" + name);
    ins(".p2align\t2");
    if (!darwin) ins(".type\t" + name + ", %function");
    label(name);
    annotate(f.loc);
    ins("stp\tx29, x30, [sp, #-16]!");
    ins("mov\tx29, sp");
    adjustSp("sub", frame);
    for (auto &r : savedRegs) ins("stur\t" + r.first + ", [x29, " + imm(-r.second) + "]");

    // Move incoming parameters to their homes (a register or a stack slot).
    std::vector<Type> ptypes;
    for (auto &p : f.params) ptypes.push_back(p->type);
    int stackBytes;
    auto locs = layoutArgs(ptypes, stackBytes);
    for (size_t i = 0; i < f.params.size(); i++) {
      const VarDecl &p = *f.params[i];
      if (locs[i].inReg) {
        std::string argReg = (isFloat(p.type) ? "s" : "w") + std::to_string(locs[i].reg);
        store(p, argReg.c_str());
      } else {
        // Caller's outgoing area starts just above our saved fp/lr pair.
        std::string in = "[x29, " + imm(16 + locs[i].offset) + "]";
        ins(std::string(darwin && p.type == Type::Bool ? "ldrb" : "ldr") + "\tw9, " + in);
        if (isFloat(p.type) && reg.count(&p)) ins("fmov\t" + reg[&p] + ", w9");
        else store(p, "w9");
      }
    }

    block(*f.body);

    // Falling off the end: return zero (sema already warned if that is reachable).
    if (f.returnType == Type::Float) ins("fmov\ts0, wzr");
    else if (f.returnType != Type::Void) ins("mov\tw0, #0");
    label(retLabel);
    for (auto &r : savedRegs) ins("ldur\t" + r.first + ", [x29, " + imm(-r.second) + "]");
    ins("mov\tsp, x29");
    ins("ldp\tx29, x30, [sp], #16");
    ins("ret");
    if (!darwin) ins(".size\t" + name + ", .-" + name);
  }

  //===--- Statements ------------------------------------------------------===//

  void block(const BlockStmt &b) {
    for (auto &s : b.stmts) stmt(*s);
  }

  void stmt(const Stmt &s) {
    annotate(s.loc);
    switch (s.kind) {
    case Stmt::ExprS: {
      auto &e = static_cast<const ExprStmt &>(s);
      if (e.expr) expr(*e.expr);
      break;
    }
    case Stmt::BlockS: block(static_cast<const BlockStmt &>(s)); break;
    case Stmt::IfS: {
      auto &i = static_cast<const IfStmt &>(s);
      std::string elseL = newLabel("else"), endL = newLabel("endif");
      branchIf(*i.cond, false, i.elseB ? elseL : endL);
      block(*i.thenB);
      if (i.elseB) {
        ins("b\t" + endL);
        label(elseL);
        block(*i.elseB);
      }
      label(endL);
      break;
    }
    case Stmt::WhileS: {
      // Loop rotation: test at the bottom so each iteration takes one branch.
      auto &w = static_cast<const WhileStmt &>(s);
      std::string bodyL = newLabel("loop"), condL = newLabel("cond");
      ins("b\t" + condL);
      label(bodyL);
      stmt(*w.body);
      label(condL);
      branchIf(*w.cond, true, bodyL);
      break;
    }
    case Stmt::ReturnS: {
      auto &r = static_cast<const ReturnStmt &>(s);
      if (r.value) expr(*r.value);
      ins("b\t" + retLabel);
      break;
    }
    }
  }

  //===--- Expressions -----------------------------------------------------===//

  // FMOV (immediate) encodes ±(16..31)/16 × 2^(-3..4) in 8 bits: 0.5, 1.0, 2.5, 3.0 ...
  static bool isFmovImmediate(float f) {
    float a = std::fabs(f);
    for (int r = -3; r <= 4; r++)
      for (int n = 16; n <= 31; n++)
        if (a == std::ldexp(n / 16.0f, r)) return true;
    return false;
  }

  static bool isLeaf(const Expr &e) {
    return e.kind == Expr::IntLit || e.kind == Expr::FloatLit || e.kind == Expr::BoolLit || e.kind == Expr::VarRef;
  }

  void expr(const Expr &e) {
    switch (e.kind) {
    case Expr::IntLit: movImm32("w0", (uint32_t) static_cast<const IntLitExpr &>(e).value); break;
    case Expr::BoolLit: ins(std::string("mov\tw0, #") + (static_cast<const BoolLitExpr &>(e).value ? "1" : "0")); break;
    case Expr::FloatLit: {
      float f = static_cast<const FloatLitExpr &>(e).value;
      uint32_t bits;
      memcpy(&bits, &f, 4);
      if (bits == 0) {
        ins("fmov\ts0, wzr");
      } else if (isFmovImmediate(f)) {
        char buf[48];
        snprintf(buf, sizeof buf, "fmov\ts0, #%.6f", f);
        ins(buf);
      } else {
        movImm32("w9", bits);
        ins("fmov\ts0, w9\t\t// " + std::to_string(f));
      }
      break;
    }
    case Expr::VarRef: {
      auto &v = static_cast<const VarRefExpr &>(e);
      load(*v.decl, isFloat(v.type) ? "s0" : "w0");
      break;
    }
    case Expr::Assign: {
      auto &a = static_cast<const AssignExpr &>(e);
      expr(*a.value);
      store(*a.decl, isFloat(a.type) ? "s0" : "w0");
      break;
    }
    case Expr::Unary: {
      auto &u = static_cast<const UnaryExpr &>(e);
      expr(*u.operand);
      if (u.op == NOT) ins("eor\tw0, w0, #1");
      else if (isFloat(u.type)) ins("fneg\ts0, s0");
      else ins("neg\tw0, w0");
      break;
    }
    case Expr::Binary: binary(static_cast<const BinaryExpr &>(e)); break;
    case Expr::Call: call(static_cast<const CallExpr &>(e)); break;
    case Expr::Cast: {
      auto &c = static_cast<const CastExpr &>(e);
      expr(*c.operand);
      Type from = c.operand->type, to = c.type;
      if (to == Type::Bool) {
        if (from == Type::Float) ins("fcmp\ts0, #0.0");
        else ins("cmp\tw0, #0");
        ins("cset\tw0, ne");
      } else if (to == Type::Float) {
        ins(from == Type::Bool ? "ucvtf\ts0, w0" : "scvtf\ts0, w0");
      } // bool -> int: already 0/1 in w0
      break;
    }
    }
  }

  void binary(const BinaryExpr &b) {
    if (b.op == AND || b.op == OR) {
      // Lazy evaluation: the RHS only runs if the LHS doesn't decide the result.
      std::string endL = newLabel(b.op == AND ? "and_end" : "or_end");
      expr(*b.lhs);
      ins((b.op == AND ? "cbz\tw0, " : "cbnz\tw0, ") + endL);
      expr(*b.rhs);
      label(endL);
      return;
    }

    bool fp = isFloat(b.operandType);
    if (isComparison(b.op)) {
      ins(std::string("cset\tw0, ") + compare(b));
      return;
    }
    Operands o = operands(b, b.op == PLUS || b.op == MINUS);
    std::string args = (fp ? "s0, " : "w0, ") + o.lhs + ", " + o.rhs;
    switch (b.op) {
    case PLUS: ins((fp ? "fadd\t" : "add\t") + args); return;
    case MINUS: ins((fp ? "fsub\t" : "sub\t") + args); return;
    case ASTERIX: ins((fp ? "fmul\t" : "mul\t") + args); return;
    case DIV: ins((fp ? "fdiv\t" : "sdiv\t") + args); return;
    case MOD:
      if (fp) {
        // No FP remainder instruction on AArch64; call libm's fmodf(lhs, rhs).
        move("s2", o.rhs, true);
        move("s0", o.lhs, true);
        move("s1", "s2", true);
        ins("bl\t" + sym("fmodf"));
      } else {
        ins("sdiv\tw2, " + o.lhs + ", " + o.rhs);
        ins("msub\tw0, w2, " + o.rhs + ", " + o.lhs); // lhs - (lhs / rhs) * rhs
      }
      return;
    }
  }

  static bool isComparison(int op) { return op == LT || op == LE || op == GT || op == GE || op == EQ || op == NE; }

  // Evaluates both operands of a binary operator. Normally the LHS ends up in
  // w1/s1 and the RHS in w0/s0. If `allowImm` and the RHS is a small integer
  // literal, the LHS goes in w0 and the RHS becomes an immediate (#0..#4095),
  // which add, sub and cmp encode directly.
  struct Operands {
    std::string lhs, rhs;
  };
  static bool containsCall(const Expr &e) {
    switch (e.kind) {
    case Expr::Call: return true;
    case Expr::Assign: return containsCall(*static_cast<const AssignExpr &>(e).value);
    case Expr::Unary: return containsCall(*static_cast<const UnaryExpr &>(e).operand);
    case Expr::Cast: return containsCall(*static_cast<const CastExpr &>(e).operand);
    case Expr::Binary: {
      auto &b = static_cast<const BinaryExpr &>(e);
      if (b.op == MOD && isFloat(b.operandType)) return true; // lowered to a call to fmodf
      return containsCall(*b.lhs) || containsCall(*b.rhs);
    }
    default: return false;
    }
  }

  static bool hasSideEffects(const Expr &e) {
    switch (e.kind) {
    case Expr::Assign: case Expr::Call: return true;
    case Expr::Unary: return hasSideEffects(*static_cast<const UnaryExpr &>(e).operand);
    case Expr::Cast: return hasSideEffects(*static_cast<const CastExpr &>(e).operand);
    case Expr::Binary: {
      auto &b = static_cast<const BinaryExpr &>(e);
      return hasSideEffects(*b.lhs) || hasSideEffects(*b.rhs);
    }
    default: return false;
    }
  }

  Operands operands(const BinaryExpr &b, bool allowImm) {
    Type t = b.operandType;
    bool fp = isFloat(t);
    std::string acc = fp ? "s0" : "w0";
    // Operands that need no code: a small immediate, or a register-allocated variable.
    std::string rhsDirect = regOf(*b.rhs);
    if (allowImm && !fp && b.rhs->kind == Expr::IntLit) {
      int v = static_cast<const IntLitExpr &>(*b.rhs).value;
      if (v >= 0 && v <= 4095) rhsDirect = imm(v);
    }
    std::string lhsDirect = regOf(*b.lhs);
    if (!rhsDirect.empty()) {
      if (!lhsDirect.empty()) return {lhsDirect, rhsDirect};
      expr(*b.lhs);
      return {acc, rhsDirect};
    }
    // Reading the LHS register after evaluating the RHS is only safe if the RHS
    // cannot assign to it (C leaves `x + (x = 1)` unsequenced; we match LLVM's
    // left-to-right order exactly).
    if (!lhsDirect.empty() && !hasSideEffects(*b.rhs)) {
      expr(*b.rhs);
      return {lhsDirect, acc};
    }
    expr(*b.lhs);
    if (isLeaf(*b.rhs)) {
      ins(fp ? "fmov\ts1, s0" : "mov\tw1, w0");
      expr(*b.rhs);
    } else {
      push(t);
      expr(*b.rhs);
      pop(t, "w1", "s1");
    }
    return fp ? Operands{"s1", "s0"} : Operands{"w1", "w0"};
  }

  // Emits cmp/fcmp for a comparison and returns the condition code that is true
  // when the comparison holds. After fcmp, "mi"/"ls" are false for unordered
  // (NaN) operands, matching LLVM's ordered olt/ole, and "ne" is true for NaN,
  // matching une.
  const char *compare(const BinaryExpr &b) {
    bool fp = isFloat(b.operandType);
    Operands o = operands(b, !fp);
    ins((fp ? "fcmp\t" : "cmp\t") + o.lhs + ", " + o.rhs);
    switch (b.op) {
    case LT: return fp ? "mi" : "lt";
    case LE: return fp ? "ls" : "le";
    case GT: return "gt";
    case GE: return "ge";
    case EQ: return "eq";
    default: return "ne";
    }
  }

  // Every AArch64 condition code has an exact complement, so inverting a
  // branch stays correct for NaN operands too.
  static const char *invert(const std::string &cc) {
    static const char *pairs[][2] = {{"lt", "ge"}, {"le", "gt"}, {"eq", "ne"}, {"mi", "pl"}, {"ls", "hi"}};
    for (auto &p : pairs) {
      if (cc == p[0]) return p[1];
      if (cc == p[1]) return p[0];
    }
    return "al";
  }

  // Jumps to `target` iff cond == when. Comparisons become cmp + b.<cc> directly
  // (no 0/1 is materialised), and && / || become chains of branches.
  void branchIf(const Expr &cond, bool when, const std::string &target) {
    if (cond.kind == Expr::Binary) {
      auto &b = static_cast<const BinaryExpr &>(cond);
      if (isComparison(b.op)) {
        std::string cc = compare(b);
        ins("b." + (when ? cc : std::string(invert(cc))) + "\t" + target);
        return;
      }
      if (b.op == AND || b.op == OR) {
        bool isAnd = b.op == AND;
        if (when != isAnd) { // (AND, jump if false) or (OR, jump if true): either side decides
          branchIf(*b.lhs, when, target);
          branchIf(*b.rhs, when, target);
        } else {
          std::string skip = newLabel("skip");
          branchIf(*b.lhs, !when, skip);
          branchIf(*b.rhs, when, target);
          label(skip);
        }
        return;
      }
    }
    if (cond.kind == Expr::Unary && static_cast<const UnaryExpr &>(cond).op == NOT) {
      branchIf(*static_cast<const UnaryExpr &>(cond).operand, !when, target);
      return;
    }
    if (cond.kind == Expr::Cast && static_cast<const CastExpr &>(cond).operand->type == Type::Float) {
      expr(*static_cast<const CastExpr &>(cond).operand);
      ins("fcmp\ts0, #0.0");
      ins(std::string(when ? "b.ne\t" : "b.eq\t") + target);
      return;
    }
    // Integer truthiness needs no compare: cbz/cbnz test the register directly.
    const Expr &value = cond.kind == Expr::Cast ? *static_cast<const CastExpr &>(cond).operand : cond;
    expr(value);
    ins((when ? "cbnz\tw0, " : "cbz\tw0, ") + target);
  }

  void call(const CallExpr &c) {
    size_t n = c.args.size();
    std::vector<Type> types;
    for (auto &a : c.args) types.push_back(a->type);
    int stackBytes;
    auto locs = layoutArgs(types, stackBytes);

    // Fast path: if no argument contains a call and all fit in registers, park
    // each value in a scratch register (w10-w17 / s16-s23), which expression
    // evaluation never touches, then move them into the argument registers.
    bool simple = stackBytes == 0;
    for (auto &a : c.args) simple = simple && !containsCall(*a);
    if (simple) {
      int nextInt = 10, nextFp = 16;
      std::vector<std::string> temps;
      for (size_t i = 0; i < n; i++) {
        bool fp = isFloat(types[i]);
        std::string direct = regOf(*c.args[i]);
        if (!direct.empty()) { // already in a callee-saved register: no copy needed
          temps.push_back(direct);
          continue;
        }
        expr(*c.args[i]);
        if (i + 1 == n) { // the last value can stay in the accumulator
          temps.push_back(fp ? "s0" : "w0");
          break;
        }
        std::string t = fp ? "s" + std::to_string(nextFp++) : "w" + std::to_string(nextInt++);
        move(t, fp ? "s0" : "w0", fp);
        temps.push_back(t);
      }
      // Sources never overlap argument registers except the accumulator, so
      // moving the accumulator first makes this parallel move safe.
      for (int pass = 0; pass < 2; pass++)
        for (size_t i = 0; i < n; i++) {
          bool fp = isFloat(types[i]);
          bool isAcc = temps[i] == (fp ? "s0" : "w0");
          if (isAcc == (pass == 0)) move((fp ? "s" : "w") + std::to_string(locs[i].reg), temps[i], fp);
        }
      ins("bl\t" + sym(c.callee));
      return;
    }

    // General path: evaluate left to right, parking each value in a 16-byte stack temp.
    for (auto &a : c.args) {
      expr(*a);
      push(a->type);
    }
    adjustSp("sub", stackBytes);
    for (size_t i = 0; i < n; i++) {
      int temp = stackBytes + 16 * (int)(n - 1 - i);
      if (locs[i].inReg) {
        std::string reg = (isFloat(types[i]) ? "s" : "w") + std::to_string(locs[i].reg);
        ins("ldr\t" + reg + ", [sp, " + imm(temp) + "]");
      } else {
        ins("ldr\tw9, [sp, " + imm(temp) + "]");
        ins(std::string(darwin && types[i] == Type::Bool ? "strb" : "str") + "\tw9, [sp, " +
            imm(locs[i].offset) + "]");
      }
    }
    ins("bl\t" + sym(c.callee));
    adjustSp("add", stackBytes + 16 * (int)n);
  }
};

} // namespace

std::string generateAArch64(const Program &prog, AArch64OS os, const std::vector<std::string> &sourceLines) {
  return A64(os, sourceLines).run(prog);
}
